--  Requirements Book: page numbers for every MS2627 Rev.01 clause.
--
--  The book is MotoStudent IX Competition Regulations Rev.01 (April 2026):
--    static/book/MS2627_MotoStudent.pdf
--    sha256 53013ec6dd272c81379dd5f709f8a76f84c5b453b265ee8f7661ecc6d8bf7669
--    5 661 437 bytes, 234 pages, printed page n = PDF page n (page_offset 0)
--
--  Each page comes from SMC_Data_Rebuild_Pack data/requirement_page_map.json
--  (sha256 319a8d4c…17369), keyed by (regs_ref, clause_key) — never by the
--  printed reference, which the Organization used twice for E.5.4.5 and
--  F.5.2.3 (clause keys E.5.4.5#2, F.5.2.3#2). It agrees with the repository's
--  own independent extraction (supabase/book/ms2627-rev-01.pages.json,
--  bookMap v1) on all 1146 clauses.
--
--  This migration records page numbers and the page count only. The PDF bytes
--  are NOT uploaded by SQL: regulation_documents.storage_path stays as it is
--  until scripts/book/upload-hosted.mjs has uploaded and verified the file in
--  that same environment.
--
--  Safe to re-run: a page that is already recorded identically is left alone;
--  a DIFFERENT page already recorded is a conflict and aborts everything.
-- =============================================================================

create or replace function maintenance.apply_requirement_pages(
  p_regs_ref text, p_page_count int, p_pages jsonb)
returns jsonb
language plpgsql
set search_path = public
as $fn$
declare
  v_conflicts text[];
  v_set int;
  v_already int;
begin
  if p_page_count is null or p_page_count < 1 then
    raise exception 'apply_requirement_pages: a page count is required' using errcode = '22023';
  end if;
  if not exists (select 1 from regulation_documents where regs_ref = p_regs_ref) then
    raise exception 'apply_requirement_pages: no regulation_documents row for %', p_regs_ref using errcode = '23514';
  end if;

  lock table clauses in share row exclusive mode;

  with pages as (
    select e->>0 as clause_key, (e->>1)::int as page from jsonb_array_elements(p_pages) e
  )
  select array_agg(problem order by problem) into v_conflicts from (
    select format('clause %s listed %s times', clause_key, count(*)) as problem
      from pages group by clause_key having count(*) > 1
    union all
    select format('clause %s: page %s is outside 1..%s', clause_key, page, p_page_count)
      from pages where page is null or page < 1 or page > p_page_count
    union all
    select format('clause %s is not a %s clause', p.clause_key, p_regs_ref)
      from pages p where not exists (
        select 1 from clauses c where c.clause_key = p.clause_key and c.regs_ref = p_regs_ref)
    union all
    select format('clause %s already records page %s, reviewed data says %s', c.clause_key, c.source_page, p.page)
      from pages p join clauses c using (clause_key)
      where c.source_page is not null and c.source_page <> p.page
    union all
    select format('regulation_documents %s records %s pages, the verified file has %s', regs_ref, page_count, p_page_count)
      from regulation_documents where regs_ref = p_regs_ref and page_count is not null and page_count <> p_page_count
  ) x;

  if v_conflicts is not null then
    raise exception E'Requirement page map refused, nothing changed:\n%', array_to_string(v_conflicts, E'\n')
      using errcode = '23514';
  end if;

  select count(*) into v_already
  from jsonb_array_elements(p_pages) e join clauses c on c.clause_key = e->>0
  where c.source_page = (e->>1)::int;

  update clauses c set source_page = (e->>1)::int
  from jsonb_array_elements(p_pages) e
  where c.clause_key = e->>0 and c.regs_ref = p_regs_ref and c.source_page is null;
  get diagnostics v_set = row_count;

  update regulation_documents set page_count = p_page_count, page_offset = 0
  where regs_ref = p_regs_ref and (page_count is distinct from p_page_count or page_offset <> 0);

  if exists (select 1 from clauses where regs_ref = p_regs_ref
               and (source_page is null or source_page < 1 or source_page > p_page_count)) then
    raise exception 'apply_requirement_pages: a % clause is still without a valid page', p_regs_ref
      using errcode = '23514';
  end if;

  return jsonb_build_object('regs_ref', p_regs_ref, 'pages_set', v_set, 'pages_already_recorded', v_already,
                            'page_count', p_page_count);
end
$fn$;

