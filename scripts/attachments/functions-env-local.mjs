#!/usr/bin/env node
// Writes supabase/functions/.env.local — the attachment and backup Edge Functions' settings for the LOCAL stack
// (docs/ultraplan Phase 2/3, requirement ATT-20) — from `supabase status`. Used by CI before
// `supabase functions serve`, and by anyone setting up a fresh checkout:
//
//   node scripts/attachments/functions-env-local.mjs
//   npx supabase functions serve --env-file supabase/functions/.env.local
//
// Local only, by construction: refuses an API URL that is not 127.0.0.1 / localhost. The S3 keys are
// the stack's fixed local demo keys, never a real credential. Existing shared secrets are kept.
import { execSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const ROOT = new URL('../..', import.meta.url).pathname
const TARGET = `${ROOT}supabase/functions/.env.local`

const status = Object.fromEntries(
  execSync('npx supabase status -o env', { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .split('\n')
    .filter((l) => /^[A-Z0-9_]+=/.test(l))
    .map((l) => {
      const i = l.indexOf('=')
      return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, '')]
    }),
)

const api = new URL(status.API_URL ?? 'http://invalid')
if (!['127.0.0.1', 'localhost'].includes(api.hostname)) {
  console.error('Refusing: the API URL is not the local stack.')
  process.exit(1)
}
for (const name of ['S3_PROTOCOL_ACCESS_KEY_ID', 'S3_PROTOCOL_ACCESS_KEY_SECRET']) {
  if (!status[name]) {
    console.error(`Refusing: \`supabase status\` has no ${name} (is [storage.s3_protocol] enabled?).`)
    process.exit(1)
  }
}

const previous = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
const purgeSecret = previous.match(/^ATTACHMENTS_PURGE_SECRET=(.+)$/m)?.[1] ?? randomBytes(24).toString('hex')
const recordSecret = previous.match(/^BACKUP_RECORD_SECRET=(.+)$/m)?.[1] ?? randomBytes(24).toString('hex')

writeFileSync(
  TARGET,
  `# LOCAL ONLY (git-ignored by .env*). Generated by scripts/attachments/functions-env-local.mjs from \`supabase status\`.
# Inside the Edge Runtime container the gateway is reached as host.docker.internal:${api.port}: storage verifies the S3
# signature against that public host, so the internal http://kong:8000 address fails with 403 (DECISIONS.md D-23).
ATTACHMENTS_S3_ENDPOINT=http://host.docker.internal:${api.port}/storage/v1/s3
ATTACHMENTS_S3_PUBLIC_ENDPOINT=http://127.0.0.1:${api.port}/storage/v1/s3
ATTACHMENTS_S3_REGION=${status.S3_PROTOCOL_REGION || 'local'}
ATTACHMENTS_S3_BUCKET=attachments-local
ATTACHMENTS_S3_ACCESS_KEY_ID=${status.S3_PROTOCOL_ACCESS_KEY_ID}
ATTACHMENTS_S3_SECRET_ACCESS_KEY=${status.S3_PROTOCOL_ACCESS_KEY_SECRET}
ATTACHMENTS_PURGE_SECRET=${purgeSecret}
# Backups bucket (Phase 4): the same local storage, another bucket.
BACKUPS_S3_ENDPOINT=http://host.docker.internal:${api.port}/storage/v1/s3
BACKUPS_S3_PUBLIC_ENDPOINT=http://127.0.0.1:${api.port}/storage/v1/s3
BACKUPS_S3_REGION=${status.S3_PROTOCOL_REGION || 'local'}
BACKUPS_S3_BUCKET=backups-local
BACKUPS_S3_ACCESS_KEY_ID=${status.S3_PROTOCOL_ACCESS_KEY_ID}
BACKUPS_S3_SECRET_ACCESS_KEY=${status.S3_PROTOCOL_ACCESS_KEY_SECRET}
BACKUP_RECORD_SECRET=${recordSecret}
`,
)
console.log(`Wrote ${TARGET.slice(ROOT.length)} for ${api.origin}.`)
